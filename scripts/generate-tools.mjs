import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const toolsDir = "agent/tools";
const sources = readdirSync("lib/tools").filter(
  (file) => file.endsWith(".ts") && !["index.ts", "context.ts", "linear.ts", "linear-calls.ts"].includes(file),
);
const marker = "// generated by scripts/generate-tools.mjs";

mkdirSync(toolsDir, { recursive: true });
for (const file of readdirSync(toolsDir)) {
  const full = path.join(toolsDir, file);
  if (readFileSync(full, "utf8").startsWith(marker)) rmSync(full);
}

let count = 0;
for (const source of sources) {
  const content = readFileSync(path.join("lib/tools", source), "utf8");
  const block = content.slice(content.indexOf("export const tools = {"));
  for (const match of block.matchAll(/^  ([a-z_]+): spec\(/gm)) {
    const name = match[1];
    const module = source.replace(/\.ts$/, "");
    writeFileSync(
      path.join(toolsDir, `${name}.ts`),
      `${marker}
import { defineTool } from "eve/tools";
import { runWithSecrets } from "../../lib/secrets.ts";
import { toolCtx } from "../../lib/tools/context.ts";
import { tools } from "../../lib/tools/${module}.ts";

const tool = tools.${name};

export default defineTool({
  description: tool.description,
  inputSchema: tool.inputSchema,
  execute: (input, ctx) => {
    const context = toolCtx(ctx);
    const use = {
      toolName: "${name}",
      userId: context.userId,
      sessionKey: context.sessionKey,
      keepPlaceholders: tool.keepSecretPlaceholders,
    };
    return runWithSecrets(use, input, (resolved) => tool.execute(resolved, context));
  },
});
`,
    );
    count += 1;
  }
}
console.log(`generated ${count} tool files`);
